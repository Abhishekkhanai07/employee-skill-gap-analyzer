"""Export generated tables and run metadata as CSV, JSON, and SQL."""

from __future__ import annotations

import json
import hashlib
import math
import os
from datetime import date, datetime
from typing import Any

import pandas as pd


TABLE_ORDER = [
    "roles", "skills", "employees", "courses", "budgets", "budget_events",
    "role_skill_targets", "course_skills", "prerequisites",
    "enrollments", "enrollment_events", "completions", "employee_skills", "skill_gaps",
    "recommendations", "learning_paths", "career_pathways",
]


def _sql_value(value: Any) -> str:
    if pd.isna(value):
        return "NULL"
    if isinstance(value, (bool,)):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        if isinstance(value, float) and not math.isfinite(value):
            return "NULL"
        return str(value)
    if isinstance(value, (date, datetime, pd.Timestamp)):
        return "'" + value.isoformat().replace("'", "''") + "'"
    return "'" + str(value).replace("'", "''") + "'"


def _write_sql_seed(data: dict[str, pd.DataFrame], path: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as output:
        output.write("-- Generated synthetic seed data. Apply schema.sql before this file.\n")
        for table in TABLE_ORDER:
            frame = data.get(table)
            if frame is None or frame.empty:
                continue
            columns = ", ".join(f'"{column}"' for column in frame.columns)
            output.write(f'INSERT INTO "{table}" ({columns}) VALUES\n')
            values = []
            for row in frame.itertuples(index=False, name=None):
                values.append("(" + ", ".join(_sql_value(value) for value in row) + ")")
            output.write(",\n".join(values) + ";\n\n")


def _write_text(path: str, text: str) -> None:
    with open(path, "w", encoding="utf-8", newline="\n") as output:
        output.write(text)


def _sha256_file(path: str) -> str:
    digest = hashlib.sha256()
    with open(path, "rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def export_all(
    data: dict[str, pd.DataFrame],
    ground_truth_df: pd.DataFrame,
    validation_summary: dict[str, Any],
    outcomes: dict[str, Any],
    output_dir: str,
    seed: int,
    formats: list[str] | None = None,
) -> list[str]:
    os.makedirs(output_dir, exist_ok=True)
    formats = formats or ["csv", "json", "sql"]
    exported: list[str] = []
    for table, frame in data.items():
        if table == "ground_truth":
            continue
        if "csv" in formats:
            path = os.path.join(output_dir, f"{table}.csv")
            frame.to_csv(path, index=False, lineterminator="\n")
            exported.append(path)
        if "json" in formats:
            path = os.path.join(output_dir, f"{table}.json")
            with open(path, "w", encoding="utf-8") as output:
                output.write(frame.to_json(orient="records", indent=2, date_format="iso"))
                output.write("\n")
            exported.append(path)

    for format_name, writer in [
        ("csv", lambda path: ground_truth_df.to_csv(path, index=False, lineterminator="\n")),
        ("json", lambda path: _write_text(
            path, ground_truth_df.to_json(orient="records", indent=2, date_format="iso") + "\n"
        )),
    ]:
        if format_name in formats:
            path = os.path.join(output_dir, f"ground_truth.{format_name}")
            writer(path)
            exported.append(path)
    if "sql" in formats:
        path = os.path.join(output_dir, "seed.sql")
        _write_sql_seed(data, path)
        exported.append(path)

    summary_paths = [
        ("validation_summary.json", validation_summary),
        ("outcome_summary.json", outcomes),
    ]
    for filename, payload in summary_paths:
        path = os.path.join(output_dir, filename)
        with open(path, "w", encoding="utf-8") as output:
            json.dump(payload, output, indent=2, sort_keys=True, default=str)
            output.write("\n")
        exported.append(path)

    metadata = {
        "seed": seed,
        "generator": "main.py",
        "row_counts": {name: int(len(frame)) for name, frame in data.items()},
        "ground_truth_rows": int(len(ground_truth_df)),
        "validation": validation_summary,
        "outcomes": outcomes,
        "source": "synthetic data generated by this repository; no external datasets used",
        "generated_files_sha256": {
            os.path.basename(file_path): _sha256_file(file_path)
            for file_path in exported
        },
    }
    for filename in ["manifest.json", "source_manifest.json"]:
        path = os.path.join(output_dir, filename)
        with open(path, "w", encoding="utf-8") as output:
            json.dump(metadata, output, indent=2, sort_keys=True)
            output.write("\n")
        exported.append(path)
    return exported
